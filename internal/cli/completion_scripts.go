package cli

import (
	"bytes"
	"fmt"
	"io"
	"strings"

	"github.com/spf13/cobra"
)

// Keep Cobra's generators and completion protocol, but invoke the executable
// with argument arrays. A literal shell metacharacter in a home or argument is
// data: completion must never evaluate it as another command. Replacements are
// checked so an upstream template change cannot silently lose this boundary.
func generateCompletionScript(root *cobra.Command, shell string, out io.Writer) error {
	var generated bytes.Buffer
	var err error
	switch shell {
	case "bash":
		err = root.GenBashCompletionV2(&generated, true)
	case "zsh":
		err = root.GenZshCompletion(&generated)
	case "fish":
		err = root.GenFishCompletion(&generated, true)
	}
	if err != nil {
		return err
	}
	script := generated.String()
	replace := func(old, new string) error {
		if strings.Count(script, old) != 1 {
			return fmt.Errorf("unsupported %s completion template", shell)
		}
		script = strings.Replace(script, old, new, 1)
		return nil
	}
	changes := [][2]string{}
	switch shell {
	case "bash":
		changes = append(changes, [2]string{`out=$(eval "${requestComp}" 2>/dev/null)`, `if [[ -z ${cur} && ${lastChar} != = ]]; then
        if [[ ${#args[@]} -eq 0 || -n ${args[${#args[@]}-1]} ]]; then
            args+=("")
        fi
    fi
    out=$("${words[0]}" __complete "${args[@]}" 2>/dev/null)`})
	case "zsh":
		changes = append(changes,
			[2]string{`words=("${=words[1,CURRENT]}")`, `words=("${words[@]:0:$CURRENT}")`},
			[2]string{`local -a completions`, `local -a completions requestArgs describeOptions
    local flagPrefixValue`},
			[2]string{`flagPrefix="-P ${BASH_REMATCH}"`, `flagPrefixValue=${BASH_REMATCH}
        flagPrefix="-P ${(q)flagPrefixValue}"`},
			[2]string{`out=$(eval ${requestComp} 2>/dev/null)`, `requestArgs=("${words[@]:1}")
    if [[ -z ${lastChar} && ( ${#requestArgs[@]} -eq 0 || -n ${requestArgs[-1]} ) ]]; then
        requestArgs+=("")
    fi
    out=$("${words[1]}" __complete "${requestArgs[@]}" 2>/dev/null)`},
			[2]string{`if eval _describe $keepOrder "completions" completions $flagPrefix $noSpace; then`, `describeOptions=()
        [[ -n ${keepOrder} ]] && describeOptions+=("${keepOrder}")
        [[ -n ${flagPrefixValue} ]] && describeOptions+=(-P "${flagPrefixValue}")
        [[ -n ${noSpace} ]] && describeOptions+=(-S "")
        if _describe "${describeOptions[@]}" "completions" completions; then`})
	case "fish":
		changes = append(changes,
			[2]string{`set -l args (commandline -opc)`, `set -l args (commandline -xpc)`},
			[2]string{`set -l results (eval $requestComp 2> /dev/null)`, `set -l requestLast (string unescape -- (commandline -ct))
    if test (count $requestLast) -eq 0
        set requestLast ""
    end
    set -l results (env ARM_ACTIVE_HELP=0 $args[1] __complete $args[2..-1] "$requestLast" 2> /dev/null)`})
	}
	for _, change := range changes {
		if err := replace(change[0], change[1]); err != nil {
			return err
		}
	}
	_, err = io.WriteString(out, script)
	return err
}
